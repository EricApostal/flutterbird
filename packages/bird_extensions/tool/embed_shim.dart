// Regenerates lib/src/shim/shim_source.dart from lib/src/shim/browser_shim.js.
//
// The shim is a real .js file so that it can be tested under Node and read as
// JavaScript; this embeds it into Dart so that the app needs no asset for it.
//
//   dart run tool/embed_shim.dart
import 'dart:io';

void main() {
  final script = File('lib/src/shim/browser_shim.js');
  final output = File('lib/src/shim/shim_source.dart');

  final source = script.readAsStringSync();
  if (source.contains("'''")) {
    stderr.writeln("browser_shim.js contains ''' and cannot be embedded raw");
    exit(1);
  }

  output.writeAsStringSync(
    '// GENERATED by tool/embed_shim.dart from browser_shim.js. Do not edit.\n'
    "// ignore_for_file: unnecessary_raw_strings\n"
    '\n'
    '/// The JavaScript that builds `browser` and `chrome` in an extension world.\n'
    "const String browserShimSource = r'''\n"
    '$source'
    "''';\n",
  );
  stdout.writeln('Wrote ${output.path} (${source.length} bytes of JavaScript)');
}
